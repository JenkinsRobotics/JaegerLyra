"""Compare constant versus 8/24-dimensional changing source representations.

No human listening, no new model downloads, no autoplay. Every model is fitted
only to the reference, never the held-out utterance. Same oscillator/filter path.
"""
import os
os.environ.setdefault('OPENBLAS_NUM_THREADS','1')
os.environ.setdefault('VECLIB_MAXIMUM_THREADS','1')
os.environ['HF_HUB_OFFLINE']='1'
import argparse,json,time
from pathlib import Path
import numpy as np
import soundfile as sf
import torch,torchaudio
from speechbrain.inference.classifiers import EncoderClassifier
from continuous_source import ContinuousSource
from excitation import GeneratedVoicebox,VocalControls
from benchmark_excitation import analyze
from benchmark_voicebox import transcribe,errors,f0_track

ROOT=Path(__file__).resolve().parents[2]
OUT=ROOT/'evidence/generated-excitation/continuous-source'
FIXTURES=ROOT/'evidence/voice-fixtures'


def main():
    global OUT
    parser=argparse.ArgumentParser();parser.add_argument('--step-source',action='store_true')
    parser.add_argument('--validation',action='store_true');args=parser.parse_args()
    if not args.step_source:OUT=OUT/'smooth'
    if args.validation:OUT=OUT/'validation'
    OUT.mkdir(exist_ok=True,parents=True)
    torch.set_num_threads(4)
    folder=ROOT/'models/speaker-eval'
    evaluator=EncoderClassifier.from_hparams(source=str(folder),savedir=str(folder),
        overrides={'pretrained_path':str(folder)},run_opts={'device':'cpu'})
    def embedding(audio):
        data=torch.from_numpy(audio.astype(np.float32)).unsqueeze(0)
        data=torchaudio.functional.resample(data,24000,16000)
        with torch.inference_mode():value=evaluator.encode_batch(data).flatten()
        return value/torch.linalg.vector_norm(value)
    report={'scope':'Continuous source representation ablation, no linguistic or autonomous speech generation',
        'analysis':'Centered 40 ms window with 15 ms explicit lookahead',
        'training':'Classical PCA on aligned normalized harmonic descriptors from each short synthetic reference',
        'noGlobalBackpropagation':True,'discreteCodebook':False,
        'decoderReceivesOriginalResidual':False,'dimensions':[0,8,24],
        'limits':['Dynamic source coordinates are inferred from input audio; not generated by the predictive model','Filter/content still comes from input speech','ECAPA scores are diagnostics, not percentages or listener ratings'],
        'sourceInterpolation':'step' if args.step_source else 'linear complex coefficients over each 10ms frame',
        'sourceNormalization':'Interpolated endpoint power; preserves fades during phase changes',
        'validation':args.validation,'models':[],'results':[]}
    for speaker in ('af_heart','am_michael'):
        reference,rate=sf.read(FIXTURES/f'{speaker}-reference.wav');assert rate==24000
        reference_frames=analyze(reference,True)
        full,count=ContinuousSource.fit(reference_frames,24)
        np.savez(OUT/f'{speaker}-source.npz',mean=full.mean,basis=full.basis)
        anchor=embedding(reference)
        if args.validation:
            manifest=json.loads((ROOT/'evidence/streaming-voicebox/validation/manifest.json').read_text())
            items=[row for row in manifest['clips'] if row['speaker']==speaker]
            cases=[(item['name'],ROOT/item['file'],item['text']) for item in items]
        else:
            path=FIXTURES/f'{speaker}-heldout.wav'
            cases=[(speaker,path,json.loads(path.with_suffix('.json').read_text())['text'])]
        for label,path,text in cases:
            evaluate_case(label,path,text,speaker,full,anchor,embedding,report,args)


def evaluate_case(label,path,text,speaker,full,anchor,embedding,report,args):
    original,rate=sf.read(path)
    frames=analyze(original,True)
    _,original_pitch=f0_track(original)
    if not any(row['speaker']==speaker for row in report['models']):
        report['models'].append({'speaker':speaker,'modelFile':f'{speaker}-source.npz','training':'Only original reference clip'})
    for dimensions in (0,8,24):
        model=ContinuousSource(full.mean,full.basis[:dimensions])
        # Encoder sees analysis windows; decoder receives only these tuples.
        started=time.perf_counter()
        encoded=[(VocalControls.from_frame(frame),model.encode(frame)) for frame in frames]
        encode_seconds=time.perf_counter()-started
        source=GeneratedVoicebox(smooth_source=not args.step_source);output=[];times=[]
        for control,coordinates in encoded:
            started=time.perf_counter()
            output.append(source.push(control,harmonics=model.decode(coordinates)))
            times.append((time.perf_counter()-started)*1000)
        audio=np.concatenate(output)
        peak=float(np.max(np.abs(audio)))
        gain=min(float(np.sqrt(np.mean(original**2))/max(1e-9,np.sqrt(np.mean(audio**2)))),.88/max(1e-9,peak))
        audio*=gain
        output_path=OUT/f'{label}-source{dimensions}.wav'
        sf.write(output_path,np.rint(audio*32768).astype(np.int16),rate,subtype='PCM_16')
        heard=transcribe(output_path)
        _,generated_pitch=f0_track(audio)
        mask=(original_pitch>0)&(generated_pitch>0)
        cents=np.abs(1200*np.log2(generated_pitch[mask]/original_pitch[mask]))
        vector=embedding(audio);original_vector=embedding(original)
        row={'speaker':speaker,'fixture':label,'dimensions':dimensions,'file':str(output_path.relative_to(ROOT)),
            'text':heard,**errors(text,heard),'identityCosine':float(torch.dot(vector,anchor)),
            'originalIdentityCosine':float(torch.dot(original_vector,anchor)),
            'medianPitchErrorCents':float(np.median(cents)),
            'voicingAgreement':float(np.mean((original_pitch>0)==(generated_pitch>0))),
            'encodedSourceScalarsPerFrame':dimensions,'totalContinuousScalarsPerFrame':24+dimensions,
            'encodeSeconds':encode_seconds,'synthesisMsP95':float(np.percentile(times,95)),
            'rawPeak':peak,'auditionGain':gain}
        report['results'].append(row)
        (OUT/'report.json').write_text(json.dumps(report,indent=2)+'\n')
        print(json.dumps(row),flush=True)

if __name__=='__main__':main()
