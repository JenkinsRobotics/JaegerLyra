"""Check authored pitch/duration changes with a fixed neural waveform renderer.

These are edits of captured articulation. Same-edit original-PCM comparisons
isolate the neural reconstruction loss; they do not prove naturalness of the
edit itself. Pitch/words/identity are evaluated separately and failures retained.
"""
import os
os.environ.setdefault('OPENBLAS_NUM_THREADS','1')
os.environ.setdefault('VECLIB_MAXIMUM_THREADS','1')
os.environ['HF_HUB_OFFLINE']='1'
import argparse,hashlib,json,time
from pathlib import Path
import numpy as np
import soundfile as sf
import torch,torchaudio
from speechbrain.inference.classifiers import EncoderClassifier
from neural_waveform import load_model,RATE
from neural_performance import (compile_performance,save_performance,load_performance,
    render_performance,pulse_resynthesis,PerformanceControls)
from benchmark_voicebox import transcribe,errors,f0_track
from benchmark_source_ceiling import spectral_error
from benchmark_free_running import save_audio
from develop_neural_fidelity import snr

ROOT=Path(__file__).resolve().parents[2]
OUT=ROOT/'evidence/neural-performance/v2'


def pitch_reference(times,source_times,source_f0,controls):
    at=times/controls.duration_scale
    right=np.clip(np.searchsorted(source_times,at),0,len(source_times)-1)
    left=np.maximum(right-1,0)
    nearest=np.where(abs(at-source_times[left])<=abs(at-source_times[right]),left,right)
    voiced=source_f0[nearest]>0
    expected=np.interp(at,source_times,source_f0)
    if len(controls.note_times):expected=np.interp(times,controls.note_times,controls.note_hz)
    expected*=controls.pitch_ratio(times);expected[~voiced]=0.
    return expected


def main():
    global OUT,render_performance,pulse_resynthesis
    parser=argparse.ArgumentParser();parser.add_argument('--legacy-v1',action='store_true')
    args=parser.parse_args()
    if args.legacy_v1:
        from legacy_neural_performance_v1 import render_performance as legacy_render,pulse_resynthesis as legacy_pulses
        render_performance=legacy_render;pulse_resynthesis=legacy_pulses;OUT=ROOT/'evidence/neural-performance/v1'
    OUT.mkdir(parents=True,exist_ok=True);(OUT/'performances').mkdir(exist_ok=True)
    manifest=json.loads((ROOT/'evidence/neural-waveform/output-detail-validation/manifest.json').read_text())
    candidate=ROOT/manifest['candidate']
    if hashlib.sha256(candidate.read_bytes()).hexdigest()!=manifest['candidateSha256']:raise ValueError('Model changed')
    encoder,decoder,_=load_model(candidate)
    before=hashlib.sha256(decoder.W.tobytes()+decoder.V.tobytes()).hexdigest()
    cases=[r for r in manifest['clips'] if r['kind']=='fresh-kokoro' and r['name'].endswith(('-0','-1'))]
    if len(cases)!=6:raise ValueError('Unexpected performance panel')
    torch.set_num_threads(4);directory=ROOT/'models/speaker-eval'
    evaluator=EncoderClassifier.from_hparams(source=str(directory),savedir=str(directory),
        overrides={'pretrained_path':str(directory)},run_opts={'device':'cpu'})
    def embedding(audio):
        samples=torchaudio.functional.resample(torch.from_numpy(audio.astype(np.float32)).unsqueeze(0),RATE,16000)
        with torch.inference_mode():value=evaluator.encode_batch(samples).flatten()
        return value/torch.linalg.vector_norm(value)
    report={'scope':'Independent output pitch/duration controls over captured neural articulation; not autonomous speech or voice cloning',
        'model':manifest['candidate'],'modelSha256':manifest['candidateSha256'],
        'analysis':'Offline Praat pulse analysis during compilation; no transcript, no model fitting',
        'runtimeInputs':'Encoded performance controls, pulse timings, frozen decoder, authored pitch/duration settings',
        'renderer':'New project implementation of classical pulse-synchronous overlap/add; PCM is generated by neural decoder',
        'rendererVersion':1 if args.legacy_v1 else 2,
        'reference':'https://uvafon.hum.uva.nl/praat/manual/overlap-add.html',
        'timingScope':'Offline whole-performance decode/edit; not first-audio or live streaming latency',
        'expectedCases':len(cases)*7,'auditionGain':.5,'originals':[],'results':[],'complete':False}
    anchors={}
    for case in cases:
        original,rate=sf.read(ROOT/case['file']);assert rate==RATE
        started=time.perf_counter();performance=compile_performance(original,encoder)
        compiled=time.perf_counter()-started;artifact=OUT/'performances'/(case['name']+'.npz')
        save_performance(artifact,performance,{'sourceSha256':case['sha256'],'modelSha256':manifest['candidateSha256']})
        del performance
        performance,_=load_performance(artifact)
        original_times,original_f0=f0_track(original)
        if case['reference'] not in anchors:
            ref_audio,ref_rate=sf.read(ROOT/case['reference']);assert ref_rate==RATE
            anchors[case['reference']]=embedding(ref_audio)
        anchor=anchors[case['reference']];heard=transcribe(ROOT/case['file'])
        report['originals'].append({'fixture':case['name'],'file':case['file'],'duration':len(original)/RATE,
            'pulses':len(performance.pulses),'compileSeconds':compiled,'performance':str(artifact.relative_to(ROOT)),
            'recognition':{'text':heard,**errors(case['text'],heard)},'identityCosine':float(torch.dot(embedding(original),anchor))})
        length=len(original)/RATE
        scale=110. if case['speaker']=='am_michael' else 196.
        # Four authored pitches with short transitions, independent of source intonation.
        notes=np.array([1.,2**(2/12),2**(4/12),2**(2/12)])*scale
        times=[0.];values=[float(notes[0])]
        for index in range(1,4):
            boundary=length*index/4;times.extend([boundary-.02,boundary+.02]);values.extend([float(notes[index-1]),float(notes[index])])
        times.append(length);values.append(float(notes[-1]))
        modes={'neutral':PerformanceControls(),'up-three':PerformanceControls(pitch_semitones=3),
            'down-three':PerformanceControls(pitch_semitones=-3),'longer':PerformanceControls(duration_scale=1.25),
            'faster':PerformanceControls(duration_scale=.8),'vibrato':PerformanceControls(vibrato_cents=35,vibrato_hz=5),
            'four-notes':PerformanceControls(note_times=tuple(times),note_hz=tuple(values))}
        for name,control in modes.items():
            row={'fixture':case['name'],'mode':name,'controls':control.__dict__}
            try:
                started=time.perf_counter();output,stats=render_performance(performance,decoder,control)
                elapsed=time.perf_counter()-started
                reference,_=pulse_resynthesis(original,performance.pulses,control)
                if len(output)!=round(len(original)*control.duration_scale):raise ValueError('Output duration mismatch')
                path=OUT/(case['name']+'-'+name+'.wav');save_audio(path,output)
                truth_path=OUT/(case['name']+'-'+name+'-original-renderer.wav');save_audio(truth_path,reference)
                measured_times,pitch=f0_track(output);expected=pitch_reference(measured_times,original_times,original_f0,control)
                joint=(pitch>0)&(expected>0);cents=abs(1200*np.log2(pitch[joint]/expected[joint]))
                text=transcribe(path);reference_text=transcribe(truth_path)
                row.update({'status':'ok','file':str(path.relative_to(ROOT)),'sameEditReference':str(truth_path.relative_to(ROOT)),
                    'durationSeconds':len(output)/RATE,'rendererStats':stats,
                    'neuralVsSameEditOriginalSnrDb':snr(reference,output),
                    'spectralAgainstSameEditOriginalDb':spectral_error(reference,output)['meanAbsoluteDb'],
                    'medianPitchErrorCents':float(np.median(cents)) if len(cents) else None,
                    'p95PitchErrorCents':float(np.percentile(cents,95)) if len(cents) else None,
                    'pitchVoicingAgreement':float(np.mean((pitch>0)==(expected>0))),
                    'rawPeak':float(abs(output).max()),'renderSeconds':elapsed,'computeRealTimeFactor':elapsed/(len(output)/RATE),
                    'text':text,**errors(case['text'],text),'sameEditOriginalRecognition':{'text':reference_text,**errors(case['text'],reference_text)},
                    'identityCosine':float(torch.dot(embedding(output),anchor))})
                if name=='neutral':row['neutralMaximumDifferenceFromNeural']=float(np.max(abs(output-decoder.render(performance.matrix))))
            except ValueError as error:
                row.update({'status':'failed','error':str(error)})
            report['results'].append(row)
            (OUT/'report.json').write_text(json.dumps(report,indent=2,allow_nan=False)+'\n')
            print(json.dumps({k:v for k,v in row.items() if k not in ('file','sameEditReference','text','controls','rendererStats','sameEditOriginalRecognition')}),flush=True)
    after=hashlib.sha256(decoder.W.tobytes()+decoder.V.tobytes()).hexdigest()
    if before!=after:raise AssertionError('Output performance modified neural weights')
    report['weightsUnchanged']=True;report['complete']=True
    (OUT/'report.json').write_text(json.dumps(report,indent=2,allow_nan=False)+'\n')


if __name__=='__main__':main()
